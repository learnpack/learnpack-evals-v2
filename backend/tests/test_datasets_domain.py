"""The rules of a dataset and its versions (ADR-0058) — pure domain, no DB."""

import pytest

from app.modules.datasets.domain.dataset import (
    Dataset,
    DatasetVersion,
    EmptyMembership,
    InvalidDataset,
    UnchangedMembership,
    canonical_members,
    member_set_hash,
)
from app.shared.domain.ids import new_id


def make_dataset(**overrides) -> Dataset:
    base = {"id": new_id(), "name": "SME reference set", "created_by": new_id()}
    return Dataset(**(base | overrides))


def declared(members: list, note: str = "the first forty") -> tuple[Dataset, DatasetVersion]:
    """A dataset as `DeclareDataset` leaves it: named, with v1 already frozen."""
    dataset = make_dataset()
    version = dataset.mint_version(
        version_id=new_id(), members=members, note=note, created_by=dataset.created_by
    )
    return dataset, version


# --- The dataset itself ---------------------------------------------------------------


def test_a_dataset_needs_a_name():
    with pytest.raises(InvalidDataset):
        make_dataset(name="   ")


def test_a_dataset_with_no_version_has_no_latest():
    assert make_dataset().latest_version is None


# --- Minting a version ----------------------------------------------------------------


def test_the_first_version_is_ordinal_one_and_the_latest():
    dataset, version = declared([new_id(), new_id()])

    assert version.ordinal == 1
    assert dataset.latest_version is version
    assert len(dataset.versions) == 1


def test_versions_are_numbered_in_the_order_they_were_frozen():
    first = [new_id(), new_id()]
    dataset, _ = declared(first)

    second = dataset.mint_version(
        version_id=new_id(),
        members=[*first, new_id()],
        note="added the course generated by 2.0.0",
        created_by=dataset.created_by,
    )

    assert [v.ordinal for v in dataset.versions] == [1, 2]
    assert dataset.latest_version is second


def test_a_version_needs_at_least_one_course():
    dataset = make_dataset()
    with pytest.raises(EmptyMembership):
        dataset.mint_version(
            version_id=new_id(), members=[], note="nothing", created_by=dataset.created_by
        )


def test_a_version_needs_a_note_saying_why_it_exists():
    dataset = make_dataset()
    with pytest.raises(InvalidDataset):
        dataset.mint_version(
            version_id=new_id(), members=[new_id()], note="  ", created_by=dataset.created_by
        )


def test_a_refused_version_leaves_the_line_untouched():
    dataset, _ = declared([new_id()])

    with pytest.raises(EmptyMembership):
        dataset.mint_version(
            version_id=new_id(), members=[], note="nothing", created_by=dataset.created_by
        )

    assert len(dataset.versions) == 1


# --- The no-op rule -------------------------------------------------------------------


def test_the_same_membership_is_a_no_op_not_a_version():
    members = [new_id(), new_id()]
    dataset, _ = declared(members)

    with pytest.raises(UnchangedMembership):
        dataset.mint_version(
            version_id=new_id(),
            members=members,
            note="typed the same list again",
            created_by=dataset.created_by,
        )
    assert len(dataset.versions) == 1


def test_order_and_repetition_are_not_a_change():
    first, second = new_id(), new_id()
    dataset, _ = declared([first, second])

    with pytest.raises(UnchangedMembership):
        dataset.mint_version(
            version_id=new_id(),
            members=[second, first, first],
            note="same set, pasted differently",
            created_by=dataset.created_by,
        )


def test_a_membership_that_returns_to_an_older_one_is_a_new_version():
    """Only the CURRENT version is compared: going back to v1's set is a real change from v2,
    and refusing it would refuse a true statement about the set today."""
    first = [new_id(), new_id()]
    dataset, _ = declared(first)
    dataset.mint_version(
        version_id=new_id(),
        members=[*first, new_id()],
        note="added one",
        created_by=dataset.created_by,
    )

    third = dataset.mint_version(
        version_id=new_id(),
        members=first,
        note="that course was withdrawn",
        created_by=dataset.created_by,
    )

    assert third.ordinal == 3
    assert third.member_set_hash == dataset.versions[0].member_set_hash


# --- Renaming -------------------------------------------------------------------------


def test_renaming_does_not_mint_a_version():
    dataset, _ = declared([new_id()])

    assert dataset.rename("Reference set — round 2", "the same courses") is True

    assert dataset.name == "Reference set — round 2"
    assert len(dataset.versions) == 1


def test_renaming_to_the_same_label_changes_nothing():
    dataset, _ = declared([new_id()])
    dataset.rename("Reference set", None)

    assert dataset.rename("Reference set", None) is False


def test_a_rename_cannot_blank_the_name():
    dataset, _ = declared([new_id()])

    with pytest.raises(InvalidDataset):
        dataset.rename("   ", None)


# --- Identity by contents -------------------------------------------------------------


def test_the_hash_is_the_set_not_the_list():
    first, second = new_id(), new_id()

    assert member_set_hash([first, second]) == member_set_hash([second, first, first])
    assert member_set_hash([first]) != member_set_hash([first, second])


def test_members_are_stored_de_duplicated_and_ordered():
    first, second = new_id(), new_id()

    assert canonical_members([second, first, second]) == tuple(sorted({first, second}, key=str))


def test_a_version_stores_the_canonical_membership():
    first, second = new_id(), new_id()
    _, version = declared([second, first, second])

    assert version.members == canonical_members([first, second])
    assert version.member_set_hash == member_set_hash([first, second])
