"""HTTP adapters for Datasets: declaring a set, freezing a version, correcting a label
(ADR-0058).
"""

from datetime import datetime
from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel, Field

from app.modules.datasets.application.declare_dataset import (
    DeclareDataset,
    DeclareDatasetCommand,
)
from app.modules.datasets.application.mint_dataset_version import (
    MintDatasetVersion,
    MintDatasetVersionCommand,
)
from app.modules.datasets.application.rename_dataset import RenameDataset, RenameDatasetCommand
from app.modules.datasets.domain.dataset import (
    Dataset,
    DatasetNotFound,
    EmptyMembership,
    InvalidDataset,
    UnchangedMembership,
)
from app.modules.datasets.infrastructure.repository import SqlAlchemyDatasetRepository
from app.modules.evaluand_registry.public import (
    EvaluandRegistryQueries,
    get_evaluand_registry_queries,
)
from app.platform.security import AdminAssessor
from app.platform.uow import UnitOfWork, get_uow

Uow = Annotated[UnitOfWork, Depends(get_uow)]
# Other modules are reached only through their public query surface (ARCHITECTURE.md §3).
Contents = Annotated[EvaluandRegistryQueries, Depends(get_evaluand_registry_queries)]

admin_router = APIRouter(prefix="/admin/datasets", tags=["datasets-admin"])


# --------------------------------------------------------------------------- schemas


class DeclareDatasetRequest(BaseModel):
    name: str = Field(min_length=1, examples=["SME reference set"])
    description: str | None = None
    # Required from the first version, like every one after it: a set whose reason nobody
    # wrote down cannot be told apart later from one that changed by accident (ADR-0058 §3).
    note: str = Field(min_length=1, examples=["The 40 courses of the first reference campaign"])
    content_ids: list[UUID]


class MintDatasetVersionRequest(BaseModel):
    note: str = Field(min_length=1, examples=["Added the 8 courses generated by 2.0.0"])
    content_ids: list[UUID]


class RenameDatasetRequest(BaseModel):
    """The label, replaced whole (ADR-0055's shape): one dialog edits both fields, so an
    omitted description clears it rather than meaning anything subtler."""

    name: str = Field(min_length=1, examples=["SME reference set"])
    description: str | None = None


class DatasetVersionResponse(BaseModel):
    version_id: UUID
    ordinal: int
    note: str
    member_set_hash: str
    content_ids: list[UUID]
    created_by: UUID
    created_at: datetime | None


class DatasetResponse(BaseModel):
    """One shape for both reads. The list could carry counts instead of members, and then the
    two endpoints would be two things that can drift into meaning different sets."""

    dataset_id: UUID
    name: str
    description: str | None
    created_by: UUID
    created_at: datetime | None
    # Oldest first: the ordinals read as the line they are.
    versions: list[DatasetVersionResponse]


# --------------------------------------------------------------------------- helpers


def _dataset_response(dataset: Dataset) -> DatasetResponse:
    return DatasetResponse(
        dataset_id=dataset.id,
        name=dataset.name,
        description=dataset.description,
        created_by=dataset.created_by,
        created_at=dataset.created_at,
        versions=[
            DatasetVersionResponse(
                version_id=version.id,
                ordinal=version.ordinal,
                note=version.note,
                member_set_hash=version.member_set_hash,
                content_ids=list(version.members),
                created_by=version.created_by,
                created_at=version.created_at,
            )
            for version in dataset.versions
        ],
    )


def _require_registered(contents: Contents, content_ids: list[UUID]) -> None:
    """Members are contents this store knows about — checked here, because the application
    layer may not see another module (ARCHITECTURE.md §3), and refused by naming the ids.

    There is no foreign key underneath this (DATA_MODEL §8), so this is the only gate; a
    content is never retired (ADR-0033), so passing it once means passing it forever.
    """
    known = {snapshot.content_id for snapshot in contents.list_content_snapshots()}
    unknown = [str(content_id) for content_id in content_ids if content_id not in known]
    if unknown:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail=f"not registered courses: {', '.join(sorted(unknown))}",
        )


# --------------------------------------------------------------------------- admin


@admin_router.get("", response_model=list[DatasetResponse])
def list_datasets(admin: AdminAssessor, uow: Uow) -> list[DatasetResponse]:
    """Every dataset, oldest-declared first, each with its version line."""
    datasets = SqlAlchemyDatasetRepository(uow.session).list_all()
    return [_dataset_response(dataset) for dataset in datasets]


@admin_router.get("/{dataset_id}", response_model=DatasetResponse)
def get_dataset(dataset_id: UUID, admin: AdminAssessor, uow: Uow) -> DatasetResponse:
    dataset = SqlAlchemyDatasetRepository(uow.session).get(dataset_id)
    if dataset is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="dataset not found")
    return _dataset_response(dataset)


@admin_router.post("", status_code=status.HTTP_201_CREATED, response_model=DatasetResponse)
def declare_dataset(
    request: DeclareDatasetRequest, admin: AdminAssessor, uow: Uow, contents: Contents
) -> DatasetResponse:
    """Name a set and freeze its first version, in one act (ADR-0058 §1)."""
    _require_registered(contents, request.content_ids)

    use_case = DeclareDataset(
        datasets=SqlAlchemyDatasetRepository(uow.session), publisher=uow.events, uow=uow
    )
    try:
        dataset = use_case(
            DeclareDatasetCommand(
                name=request.name,
                description=request.description,
                note=request.note,
                members=request.content_ids,
                declared_by=admin.assessor_id,
            )
        )
    except (InvalidDataset, EmptyMembership) as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail=str(exc)
        ) from exc
    return _dataset_response(dataset)


@admin_router.post(
    "/{dataset_id}/versions", status_code=status.HTTP_201_CREATED, response_model=DatasetResponse
)
def mint_dataset_version(
    dataset_id: UUID,
    request: MintDatasetVersionRequest,
    admin: AdminAssessor,
    uow: Uow,
    contents: Contents,
) -> DatasetResponse:
    """Freeze the next membership. A membership equal to the current one is refused (409)."""
    _require_registered(contents, request.content_ids)

    use_case = MintDatasetVersion(
        datasets=SqlAlchemyDatasetRepository(uow.session), publisher=uow.events, uow=uow
    )
    try:
        dataset, _ = use_case(
            MintDatasetVersionCommand(
                dataset_id=dataset_id,
                note=request.note,
                members=request.content_ids,
                created_by=admin.assessor_id,
            )
        )
    except DatasetNotFound as exc:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="dataset not found"
        ) from exc
    except UnchangedMembership as exc:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(exc)) from exc
    except (InvalidDataset, EmptyMembership) as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail=str(exc)
        ) from exc
    return _dataset_response(dataset)


@admin_router.patch("/{dataset_id}", response_model=DatasetResponse)
def rename_dataset(
    dataset_id: UUID, request: RenameDatasetRequest, admin: AdminAssessor, uow: Uow
) -> DatasetResponse:
    """Correct the label. This mints no version — the set did not move (ADR-0058 §2)."""
    use_case = RenameDataset(
        datasets=SqlAlchemyDatasetRepository(uow.session), publisher=uow.events, uow=uow
    )
    try:
        dataset = use_case(
            RenameDatasetCommand(
                dataset_id=dataset_id,
                name=request.name,
                description=request.description,
                renamed_by=admin.assessor_id,
            )
        )
    except DatasetNotFound as exc:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="dataset not found"
        ) from exc
    except InvalidDataset as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, detail=str(exc)
        ) from exc
    return _dataset_response(dataset)
